import type { Exam } from '../types'
import { demoHash, stableStringify, totalQuestions } from './utils'

export const SEAL_LABEL = 'Seal/sign simulation — not a cryptographic signature.'

export function previewPackageId(exam: Pick<Exam, 'id' | 'subjectCode'>): string {
  return `PKG-${demoHash(`${exam.id}:${exam.subjectCode}`).toUpperCase()}`
}

export function packageFileName(exam: Exam, packageId: string): string {
  return `exam-package_${exam.subjectCode}_${exam.classSection}_${exam.examType}_${packageId}.json`
}

export function buildPackage(exam: Exam, packageId: string, createdAt: string) {
  const metadata = {
    examId: exam.id,
    department: exam.department,
    subjectCode: exam.subjectCode,
    subject: exam.subject,
    classSection: exam.classSection,
    semester: exam.semester,
    examType: exam.examType,
    date: exam.date,
    startTime: exam.startTime,
    durationMinutes: exam.durationMinutes,
  }
  const modules = exam.moduleQuestions.map((questions, i) => ({ module: i + 1, questions }))
  const seal = demoHash(stableStringify({ packageId, createdAt, exam: metadata, modules }))

  return {
    type: 'exam-package-demo',
    schemaVersion: 1,
    notice:
      'DEMO PACKAGE generated by a browser-only simulation. It is not encrypted and not cryptographically signed.',
    packageId,
    createdAt,
    exam: metadata,
    modules,
    totalQuestions: totalQuestions(exam),
    seal: {
      method: 'FNV-1a demo checksum (not cryptographic)',
      value: seal,
      note: SEAL_LABEL,
    },
  }
}

